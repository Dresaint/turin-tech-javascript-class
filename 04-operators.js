// operators are the signs like + - * /
// operands are the number added together


// addition
const sumTwoNumbers = 3 + 6;
console.log(sumTwoNumbers);

// multiplication
const salary = 100000;
const lateFee = 5000;
const numberOfLateness = 2;
const tatalLatenessFee = lateFee * numberOfLateness;
console.log(tatalLatenessFee); 

// subtraction
const nextSalary = salary - tatalLatenessFee;
console.log(nextSalary)

// Division

console.log(30 / 5);

// modulus (remainder)
console.log(11 & 3);
console.log(50 & 5);

// Exponentiation (raise to the power of)
console.log(5 ** 2);

// Increment (+1)
let count = 0;
count++;
count++;
// count = count + 1
console.log(count);

// Decrement (-1)
count--;
// count = count - 1
console.log(count)

// post increment
let score = 90;
const myScore = score++   
console.log(myScore);
console.log(score);

// pre increment
let result = 80;
const myResult = ++result
console.log(myResult);
console.log(result);

let reCount = 4;
reCount--;
console.log(reCount);