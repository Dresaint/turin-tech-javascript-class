// Greater than (>)
console.log(10 > 15);

// less than (<)
 console.log(15 < 100);

//  Greater than or equal to (>=)
console.log(18 >= 10);

// less than or equal to (<=)
console.log(5 <= 2);

// Equality operator (==)
console.log(12 == "12");
console.log(12 == 90);
console.log((3 * 4) == "12");
console.log("Hello" == "hello");

// Srtict equality Operator (===)
console.log(12 === "12");

// Inequality Operator (!=)
console.log(2 != 5);
console.log(2 != "2");

// Strict Inequality (!==)
console.log(35 !== 40);
console.log(2 !== "2");
