/*
| Method          |         Purpose |

| `Math.round()` | Round to nearest whole number |
| `Math.floor()` | Round down |
| `Math.ceil()` | Round up |
| `Math.trunc()` | Remove decimal |
| `Math.abs()` | Absolute value |
| `Math.max()` | Largest number |
| `Math.min()` | Smallest number |
| `Math.pow()` | Raise to a power |
| `Math.sqrt()` | Square root |
| `Math.random()` | Random number `0–<1` |
| `Math.PI` | Value of π |

*/

/*
1. Math.round()
Math.round() rounds a number to the nearest whole number.
console.log(Math.round(4.4)); // Output: 4
console.log(Math.round(4.5)); // Output: 5
*/

/*
2. Math.floor()
Math.floor() rounds a number down to the nearest whole number.
console.log(Math.floor(4.9)); // Output: 4
console.log(Math.floor(4.1)); // Output: 4
*/

/*
3. Math.ceil()
Math.ceil() rounds a number up to the nearest whole number.
console.log(Math.ceil(4.1)); // Output: 5
console.log(Math.ceil(4.9)); // Output: 5
*/

/*
4. Math.trunc()
Math.trunc() removes the decimal part of a number and returns the integer part.
console.log(Math.trunc(4.9)); // Output: 4
console.log(Math.trunc(4.1)); // Output: 4
*/

/*
5. Math.abs()
Math.abs() returns the absolute value of a number.
console.log(Math.abs(-4)); // Output: 4
console.log(Math.abs(4)); // Output: 4
*/

/*
6. Math.max()
Math.max() returns the largest of zero or more numbers.
console.log(Math.max(1, 2, 3, 4, 5)); // Output: 5
console.log(Math.max(-1, -2, -3, -4, -5)); // Output: -1
*/  

/*
7. Math.min()
Math.min() returns the smallest of zero or more numbers.
console.log(Math.min(1, 2, 3, 4, 5)); // Output: 1
console.log(Math.min(-1, -2, -3, -4, -5)); // Output: -5
*/

/*
8. Math.pow()
Math.pow() returns the base to the exponent power, that is, base^exponent.
console.log(Math.pow(2, 3)); // Output: 8
console.log(Math.pow(3, 2)); // Output: 9
*/

/*
9. Math.sqrt()
Math.sqrt() returns the square root of a number.
console.log(Math.sqrt(4)); // Output: 2
console.log(Math.sqrt(9)); // Output: 3
*/

/*
10. Math.random()
Math.random() returns a random number between 0 (inclusive) and 1 (exclusive).
console.log(Math.random()); // Output: a random number between 0 and 1
*/

/*
11. random whole number 
console.log(Math.floor(Math.random() * 10)); // Output: a random whole number between 1 and 10
*/

/* 
12. Random number from 1 to 10
console.log(Math.floor(Math.random() * 10) + 1); // Output: a random whole number between 1 and 10
*/

/*
13. Random number between two numbers
Math.floor(Math.random() * (max - min + 1)) + min
Math.floor(Math.random() * (10 - 5 + 1)) + 5
Math.floor(Math.random() * 6) + 5
*/

/*
14. Math.PI
Math.PI returns the value of π (pi).
console.log(Math.PI); // Output: 3.141592653589793
*/
